import {
  AlertTriangle,
  Bell,
  Briefcase,
  Calendar,
  Check,
  ChevronDown,
  ChevronLeft,
  ChevronRight,
  Clock,
  Crosshair,
  Eye,
  FileText,
  Filter,
  Globe,
  Home,
  IndianRupee,
  LogOut,
  type LucideIcon,
  Mail,
  MapPin,
  MessageCircle,
  Pencil,
  Phone,
  Plus,
  RefreshCw,
  Search,
  Send,
  Target,
  User,
  UserX,
  Users,
  Video,
  X,
  Zap,
} from 'lucide-react-native';

import { ColorName, colors } from '@/theme';

const icons = {
  alert: AlertTriangle,
  bell: Bell,
  briefcase: Briefcase,
  calendar: Calendar,
  check: Check,
  chevD: ChevronDown,
  chevL: ChevronLeft,
  chevR: ChevronRight,
  clock: Clock,
  gps: Crosshair,
  eye: Eye,
  file: FileText,
  filter: Filter,
  globe: Globe,
  home: Home,
  rupee: IndianRupee,
  logout: LogOut,
  mail: Mail,
  pin: MapPin,
  chat: MessageCircle,
  edit: Pencil,
  phone: Phone,
  plus: Plus,
  refresh: RefreshCw,
  search: Search,
  send: Send,
  target: Target,
  user: User,
  userx: UserX,
  users: Users,
  video: Video,
  x: X,
  zap: Zap,
} satisfies Record<string, LucideIcon>;

export type IconName = keyof typeof icons;

export function Icon({ name, size = 22, color = 'text' }: { name: IconName; size?: number; color?: ColorName }) {
  const Cmp = icons[name];
  return <Cmp size={size} color={colors[color]} strokeWidth={2} />;
}
